"""
Select, train and save the workout-plan model that ml_api.py serves.

Steps: load + validate the dataset, report data quality, drop exact
duplicates, make a stratified train/test split (seed 42), compare candidate
models with 5-fold cross-validation on the training split only, fit the
selected candidate on the training split, report held-out metrics once, and
save the pipeline plus a metadata file describing how it was produced.

Usage:  python train_model.py
"""

import hashlib
import json
import platform
from datetime import datetime, timezone

import joblib
import numpy as np
import pandas as pd
import sklearn
from sklearn.metrics import accuracy_score, f1_score

from workout_ml import (
    BASE_DIR, DATA_PATH, FEATURES, METADATA_PATH, MODEL_PATH, RANDOM_SEED, TARGET, TEST_SIZE, TIE_TOLERANCE,
    data_quality_summary, load_dataset, select_model, split_dataset, validate_dataset,
)


def sha256(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def train(data_path=DATA_PATH, model_path=MODEL_PATH, metadata_path=METADATA_PATH):
    raw = pd.read_csv(data_path)
    validate_dataset(raw)
    quality = data_quality_summary(raw)
    df = load_dataset(data_path)

    X_train, X_test, y_train, y_test = split_dataset(df)
    cv_results, selected, pipeline = select_model(X_train, y_train)
    pipeline.fit(X_train, y_train)

    y_pred = pipeline.predict(X_test)
    holdout = {
        "accuracy": round(float(accuracy_score(y_test, y_pred)), 4),
        "macro_f1": round(float(f1_score(y_test, y_pred, average="macro")), 4),
    }

    model_path.parent.mkdir(parents=True, exist_ok=True)
    joblib.dump(pipeline, model_path, compress=3)

    metadata = {
        "selected_model": selected,
        "selection_rule": "highest mean 5-fold CV macro-F1 on the training split among learned "
                          f"candidates; candidates within {TIE_TOLERANCE} are tied and the simplest wins",
        "cross_validation": cv_results,
        "input_features": FEATURES,
        "features_used_by_model": [str(f) for f in pipeline.named_steps["preprocess"].get_feature_names_out()],
        "target": TARGET,
        "classes": [str(c) for c in pipeline.classes_],
        "random_seed": RANDOM_SEED,
        "test_size": TEST_SIZE,
        "dataset": {
            "file": data_path.name,
            "sha256": sha256(data_path),
            "type": "SYNTHETIC - generated by generate_synthetic_data.py, not real-world data",
            "quality_before_dedup": quality,
            "rows_after_dedup": int(len(df)),
            "train_rows": int(len(X_train)),
            "test_rows": int(len(X_test)),
        },
        "holdout_metrics": holdout,
        "holdout_metrics_note": "Labels are a deterministic function of Goal and Experience, so these "
                                "scores show the model reproduces that mapping, not real-world accuracy.",
        "versions": {
            "python": platform.python_version(),
            "scikit-learn": sklearn.__version__,
            "pandas": pd.__version__,
            "numpy": np.__version__,
            "joblib": joblib.__version__,
        },
        "trained_at_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
    }
    metadata_path.parent.mkdir(parents=True, exist_ok=True)
    metadata_path.write_text(json.dumps(metadata, indent=2))
    return pipeline, metadata


def main():
    _, meta = train()
    ds = meta["dataset"]
    print(f"Dataset (SYNTHETIC): {ds['file']}  sha256 {ds['sha256'][:12]}")
    print(f"Rows: {ds['quality_before_dedup']['n_rows']} | duplicates dropped: "
          f"{ds['quality_before_dedup']['n_exact_duplicate_rows']} | train/test: {ds['train_rows']}/{ds['test_rows']}")
    print("\n5-fold CV on the training split (macro-F1 mean +/- std):")
    for name, r in meta["cross_validation"].items():
        print(f"  [{r['type']:8s}] {name:38s} {r['cv_macro_f1_mean']:.4f} +/- {r['cv_macro_f1_std']:.4f}")
    print(f"\nSelected: {meta['selected_model']} (features: {', '.join(meta['features_used_by_model'])})")
    print("Held-out metrics:", meta["holdout_metrics"])
    print("Note:", meta["holdout_metrics_note"])
    print(f"Saved {MODEL_PATH.relative_to(BASE_DIR)} and {METADATA_PATH.relative_to(BASE_DIR)}")


if __name__ == "__main__":
    main()
